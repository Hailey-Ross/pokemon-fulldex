#!/usr/bin/env python3
import re,sys
# Makes frontend/pokedaisy/pk_fly_tables_gen.h from PokeDaisy's Kotlin tables.
# Usage: python3 tools/pokedaisy/gen_fly_tables.py <pokedaisy>/app/src/main/kotlin/com/pokedaisy/app/companion/data > frontend/pokedaisy/pk_fly_tables_gen.h
# Based on PokeDaisy by Lidor Itzhari - https://github.com/lidor30/pokedaisy
D=sys.argv[1]
def block(path,name):
    s=open(path,encoding='utf-8').read()
    i=s.index('val '+name); j=s.index('\n)',i); return s[i:j]
def spots(path,name):
    out=[]
    for m in re.finditer(r'FlySpot\((\d+), (\d+), (\d+)(?:, flag = (\d+))?(?:, nameMap = (\d+))?(?:, region = (\d+))?\)',block(path,name)):
        h,x,z,f,n,r=m.groups(); out.append((int(h),int(x),int(z),int(f) if f else -1,int(n) if n else int(h),int(r) if r else 2))
    return out
T={'Platinum':D+'/Gen4TablesPlatinum.kt','HeartGold':D+'/Gen4TownMapHeartGold.kt','Black':D+'/Gen5TablesBlack.kt',
   'White':D+'/Gen5TownMapWhite.kt','Black2':D+'/Gen5TownMapBlack2.kt','White2':D+'/Gen5TownMapWhite2.kt'}
o=['// Generated by tools/pokedaisy/gen_fly_tables.py from PokeDaisy\'s companion tables (commit 0040e61) - do not edit.',
   '// Based on PokeDaisy by Lidor Itzhari - https://github.com/lidor30/pokedaisy (GNU GPL version 3).',
   '#pragma once','#include <cstdint>','','namespace PokeFly {',
   '// One of FLY\'s spots: the town\'s map header (Gen 5: its zone), the tile FLY lands on (Gen 4; x / z),',
   '// the flag that unlocks it (-1: the game is asked), the map it is named by and its region (HeartGold /',
   '// SoulSilver: 0 Johto, 1 Kanto, 2 either).',
   'struct Spot { int16_t header, x, z, flag, nameMap; int8_t region; };']
for k,p in T.items():
    s=spots(p,'flySpots'+k); assert s,k
    o.append(f'inline constexpr Spot k{k}[] = {{')
    o+= ['    {%d, %d, %d, %d, %d, %d},'%t for t in s]
    o.append('};')
hg=open(T['HeartGold'],encoding='utf-8').read()
i=hg.index('val mainMatrixHeadersHeartGold'); j=hg.index('\n)',i)
nums=[int(n) for n in re.findall(r'\d+',hg[hg.index('setOf(',i):j])]
o.append('// HeartGold / SoulSilver: the map headers on the main map matrix (the player\'s own block is on the Pokegear map).')
o.append('inline constexpr int16_t kHgMainMatrix[] = {'+', '.join(map(str,sorted(nums)))+'};')
i=hg.index('val worldMapHeartGold'); j=hg.index('\n)',i)
wm=re.findall(r'(\d+) to \((\d+) to (\d+)\)',hg[i:j])
o.append('// The other maps\' Pokegear block (MapHeader_GetWorldMapCoords): header, x, y.')
o.append('inline constexpr int16_t kHgWorldMap[][3] = {')
for a in range(0,len(wm),8): o.append('    '+' '.join('{%s, %s, %s},'%t for t in wm[a:a+8]))
o.append('};','') if False else o.append('};')
o.append('}')
print('\n'.join(o))
print(len(nums),len(wm),file=sys.stderr)
