#!/usr/bin/env python3
"""The Guide's translations: localisation/guide_translations.json -> frontend/guide_translations.h.
--check: only verify the header is up to date and every template keeps its {n} places."""
from pathlib import Path
import argparse, json, re, sys
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / 'localisation/guide_translations.json'
OUT = ROOT / 'frontend/guide_translations.h'
def render():
    d = json.loads(SRC.read_text(encoding='utf-8'))
    langs = d['languages']
    keys = set(d['tables'][langs[0]])
    for l in langs:
        t = d['tables'][l]
        if set(t) != keys: sys.exit(f'{l}: not the same keys as {langs[0]}')
        for k, v in t.items():
            if sorted(re.findall(r'\{\d\}', k)) != sorted(re.findall(r'\{\d\}', v)): sys.exit(f'{l}: places differ in {k!r}')
    lines = ['#pragma once', '// Generated by tools/localisation/generate_guide_translations.py from localisation/guide_translations.json.',
             '// The Guide in the menus\' languages (UiLang::lang: 1 es, 2 it, 3 fr, 4 de, 5 ja, 6 ko). Names in capitals stay', '// in English: the Guide is for the English games.',
             '#include <initializer_list>', '#include <string>', '#include <unordered_map>', 'namespace GuideText {',
             '// The menus\' language, set from UiLang::lang where the Guide is made (this header needs nothing else).',
             'inline int& Lang() { static int l = 0; return l; }',
             'inline const std::unordered_map<std::string, std::string>* Table(int lang) {']
    for i, l in enumerate(langs, 1):
        lines.append(f'    if (lang == {i}) {{')
        lines.append('        static const std::unordered_map<std::string, std::string> t = {')
        for k in sorted(d['tables'][l]):
            lines.append('            {' + json.dumps(k, ensure_ascii=False) + ', ' + json.dumps(d['tables'][l][k], ensure_ascii=False) + '},')
        lines.append('        };')
        lines.append('        return &t;')
        lines.append('    }')
    lines += ['    return nullptr;', '}',
              '// s in the menus\' language, or as it is.',
              'inline std::string Tr(const std::string& s) {',
              '    const auto* t = Lang() ? Table(Lang()) : nullptr;',
              '    if (!t) return s;',
              '    const auto it = t->find(s);',
              '    return it == t->end() ? s : it->second;',
              '}',
              '// A template\'s {0}, {1}... filled in.',
              'inline std::string Fmt(std::string t, std::initializer_list<std::string> args) {',
              '    int i = 0;',
              '    for (const std::string& v : args) {',
              '        const std::string k = "{" + std::to_string(i++) + "}";',
              '        for (size_t p = t.find(k); p != std::string::npos; p = t.find(k, p + v.size())) t.replace(p, k.size(), v);',
              '    }',
              '    return t;',
              '}',
              '}', '']
    return '\n'.join(lines)
if __name__ == '__main__':
    a = argparse.ArgumentParser(); a.add_argument('--check', action='store_true'); o = a.parse_args()
    text = render()
    if o.check:
        if OUT.read_text(encoding='utf-8') != text: sys.exit('frontend/guide_translations.h is out of date: run tools/localisation/generate_guide_translations.py')
        print('guide translations up to date')
    else:
        OUT.write_text(text, encoding='utf-8'); print('wrote', OUT)
