#!/usr/bin/env python3
"""Builds PKSM-Core's data files into the program (third_party/PKSM-Core/include/utils/pksmcore_data.hpp).
    embed_data.py <PKSM-Core folder> <output .cpp>
Every file under personals/ and strings/<language>/*.txt, as pksm/personals/<name> and
pksm/strings/<language>/<name>, the paths PKSMCORE_CONFIG.h makes PKSM-Core ask for."""
import os, sys

root, out = sys.argv[1], sys.argv[2]
files = []
for name in sorted(os.listdir(os.path.join(root, "personals"))):
    p = os.path.join(root, "personals", name)
    if os.path.isfile(p):
        files.append(("pksm/personals/" + name, p))
for lang in sorted(os.listdir(os.path.join(root, "strings"))):
    d = os.path.join(root, "strings", lang)
    if os.path.isdir(d):
        for name in sorted(os.listdir(d)):
            if name.endswith(".txt"):
                files.append(("pksm/strings/%s/%s" % (lang, name), os.path.join(d, name)))

lines = ["// Generated by tools/pksm/embed_data.py: PKSM-Core's data files, built in.",
         '#include "utils/pksmcore_data.hpp"', "#include <unordered_map>", "", "namespace", "{"]
for i, (key, path) in enumerate(files):
    data = open(path, "rb").read()
    body = ",".join(str(b) for b in data) or "0"
    lines.append("const unsigned char d%d[] = {%s};" % (i, body))
lines.append("}")
lines.append("")
lines.append("const std::string* pksmcore_data::builtIn(const std::string& path)")
lines.append("{")
lines.append("    static const std::unordered_map<std::string, std::string> files = {")
for i, (key, path) in enumerate(files):
    size = os.path.getsize(path)
    lines.append('        { "%s", std::string((const char*)d%d, %d) },' % (key, i, size))
lines.append("    };")
lines.append("    auto it = files.find(path);")
lines.append("    return it == files.end() ? nullptr : &it->second;")
lines.append("}")
tmp = out + ".tmp"
with open(tmp, "w") as f:
    f.write("\n".join(lines) + "\n")
os.replace(tmp, out)
print("embedded %d files" % len(files))
