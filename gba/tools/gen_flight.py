import re,sys
# Usage: gen_flight.py PATH/TO/pokedaisy/.../GameDataRecordsGen.kt > frontend/flight_records.h
src=open(sys.argv[1]).read()
NAMES=[('FLIGHT_EMERALD','Emerald'),('FLIGHT_RUBY','Ruby'),('FLIGHT_SAPPHIRE','Sapphire'),('FLIGHT_FIRERED_REV1','FireRed'),('FLIGHT_LEAFGREEN_REV0','LeafGreen'),('FLIGHT_LEAFGREEN_REV1','LeafGreen')]
def body(name):
    i=src.index('val %s: FlightFns by lazy {'%name)
    j=src.index('FlightFns(',i)+len('FlightFns(')
    d=1;k=j
    while d:
        c=src[k]
        if c=='(':d+=1
        elif c==')':d-=1
        k+=1
    return src[j:k-1]
def parse(b):
    b=re.sub(r'//[^\n]*','',b)
    out={};d=0;cur=''
    parts=[]
    for c in b:
        if c in '([':d+=1
        if c in ')]':d-=1
        if c==',' and d==0: parts.append(cur);cur=''
        else: cur+=c
    parts.append(cur)
    for p in parts:
        p=p.strip()
        if not p: continue
        k,v=p.split('=',1); out[k.strip()]=v.strip()
    return out
def num(v):
    v=v.strip().rstrip('L')
    if v in('true','false'):return 1 if v=='true' else 0
    return int(v,0)
def lst(v):
    v=v.strip()
    if v.startswith('emptyList'):return []
    m=re.match(r'(listOf|setOf)\((.*)\)$',v,re.S)
    return [num(x) for x in m.group(2).split(',') if x.strip()]
order='objectEvents playerAvatar sprites vmap connectionFlags saveBlock2Ptr main cb2Overworld lockByte paletteFade lockControls unlockControls createSprite destroySprite startSpriteAnim birdTemplate behaviorAt collisionAt elevationAt objectAt playSe seFly seFailure walkFast walkFaster spriteOffset walkCurrent walkSlide mapHeader mapGroups drawMetatileAt riderTemplate riderGfx spriteDummy riderAnim scratch drawView spriteOffsetY mapGroupsXor birdPalette birdPaletteTag objSpriteId followerRemove followerUpdate mapGridUndefined VEHICLE'.split()
fnorder='lockControls unlockControls createSprite destroySprite startSpriteAnim behaviorAt collisionAt elevationAt objectAt playSe drawMetatileAt'.split()
opt='riderTemplate riderGfx drawView birdPalette followerRemove followerUpdate'.split()
print('// Generated by tools/gen_flight.py from PokeDaisy\'s gamedata (GameDataRecordsGen.kt\'s FLIGHT_* records; GPL 3): FREE')
print('// FLIGHT\'s addresses for the English retail games, in pk_flight.h\'s order (the vehicle word 0), then the functions the')
print('// CRCs check. Do not edit.')
print('#pragma once\n#include <cstdint>\nextern \"C\" {\n#include \"pokedaisy/pk_flight.h\"\n}\nnamespace GbaFlight {\nstruct Record { const char* name; uint32_t words[PK_FLIGHT_WORDS]; uint32_t fns[17]; uint32_t crcs[17]; int nfns; uint32_t saveBlock1; bool staticBlocks; };')
print('inline const Record kRecords[] = {')
for n,label in NAMES:
    a=parse(body(n))
    w=[]
    for k in order:
        if k=='VEHICLE': w.append(0); continue
        w.append(num(a[k]) if k in a else 0)
    ids=(lst(a.get('noFly','emptyList()'))[:4]+[0xFFFF]*4)[:4]
    w+= [ids[0]|ids[1]<<16, ids[2]|ids[3]<<16]
    land=[0]*8
    for b in lst(a['landOk']): land[b//32]|=1<<(b%32)
    w+=land
    assert len(w)==56, len(w)
    fns=[num(a[k]) for k in fnorder]+[num(a[k]) for k in opt if k in a and num(a[k])]
    crcs=lst(a['codeCrcs'])
    assert len(fns)==len(crcs),(n,len(fns),len(crcs))
    sb=num(a['saveBlock1Ptr']); st=num(a.get('saveBlockStatic','false'))
    f=lambda L: ', '.join('0x%08X'%(x&0xFFFFFFFF) for x in L)
    print('    { "%s", { %s },\n      { %s },\n      { %s }, %d, 0x%08X, %s },'%(label,f(w),f(fns),f(crcs),len(fns),sb,'true' if st else 'false'))
print('};\n} // namespace GbaFlight')
